"""One settings class: the only reader of environment variables (ADR-0015)."""

from typing import Literal

from pydantic_settings import BaseSettings, SettingsConfigDict

ENV_PREFIX = "APP_"


class Settings(BaseSettings):
    """Typed, env-driven settings (from APP_* variables and an optional .env)."""

    model_config = SettingsConfigDict(env_prefix=ENV_PREFIX, env_file=".env", extra="ignore")

    environment: Literal["dev", "prod", "test"] = "dev"
    log_level: str = "INFO"


def render_env_example() -> str:
    """Render the canonical .env.example content from this class (ADR-0014)."""
    lines = [
        "# Generated by `just gen-env` from app.settings.Settings. Never edit by hand.",
    ]
    for name, field in Settings.model_fields.items():
        key = f"{ENV_PREFIX}{name.upper()}"
        default = "" if field.is_required() else field.default
        lines.append(f"{key}={default}")
    return "\n".join(lines) + "\n"
